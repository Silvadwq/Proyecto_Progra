import pandas as pd
import matplotlib.pyplot as plt

trafico = pd.read_csv("trafico_5_cruces_2024Q1.csv")

trafico.drop(['fecha', 'sensor', 'cruce', 'visibilidad_km', 'velocidad_prom'], axis=1, inplace=True)

print(trafico[["precipitacion_mm", "es_no_laborable"]].corr())

trafico["fin_de_semana"] = (trafico["dia_semana"] >= 5).astype(int)
print(trafico["es_no_laborable"].corr(trafico["fin_de_semana"]))

explicativas_num = trafico[["es_no_laborable", "fin_de_semana", "precipitacion_mm", "ocupacion"]]
print(explicativas_num.corr())

"""**Observación:** Ya que es_no_laborable y fin_de_semana tiene una correlación superior a 0.9 se debe escoger 1 y eliminar la otra. En este caso se eliminará fin_de_semana porque repite la fin de dia_semana que ya existe."""

trafico.drop(['es_no_laborable'], axis=1, inplace=True)

d_hora=pd.get_dummies(trafico["hora"], prefix="hora", dtype=int).drop(columns="hora_0")
d_dia=pd.get_dummies(trafico["dia_semana"], prefix="dia", dtype=int).drop(columns="dia_0")
d_clima=pd.get_dummies(trafico["clima"], prefix="clima", dtype=int).drop(columns="clima_Parcialmente nublado")

datos_seleccionados=trafico[["ocupacion", "precipitacion_mm", "vehiculos"]]

#Concatenar las variables numéricas y categóricas
trafico_nuevo=pd.concat([datos_seleccionados, d_hora, d_clima, d_dia], axis=1)

from sklearn.model_selection import train_test_split
entrenamiento, test=train_test_split(trafico_nuevo, test_size=0.2, random_state=42)

import statsmodels.formula.api as smf
modelo=smf.ols(formula=('vehiculos ~ precipitacion_mm + ocupacion + '
    'hora_1 + hora_2 + hora_3 + hora_4 + hora_5 + hora_6 + hora_7 + hora_8 + hora_9 + hora_10 + hora_11 + hora_12 + '
    'hora_13 + hora_14 + hora_15 + hora_16 + hora_17 + hora_18 + hora_19 + hora_20 + hora_21 + hora_22 + hora_23 + '
    'dia_1 + dia_2 + dia_3 + dia_4 + dia_5 + dia_6 + '
    'Q("clima_Lluvia ligera") + Q("clima_Lluvia moderada") + Q("clima_Lluvia intensa") + '
    'Q("clima_Niebla") + Q("clima_Nublado") + Q("clima_Tormenta")'),data=entrenamiento).fit()
print(modelo.summary())

import statsmodels.formula.api as smf
modelo=smf.ols(formula=('vehiculos ~ precipitacion_mm + ocupacion + '
    'hora_1 + hora_2 + hora_3 + hora_4 + hora_6 + hora_7 + hora_8 + hora_9 + hora_10 + hora_11 + hora_12 + '
    'hora_13 + hora_14 + hora_15 + hora_16 + hora_17 + hora_18 + hora_19 + hora_20 + hora_21 + hora_22 + hora_23 + '
    'dia_1 + dia_2 + dia_4 + dia_5 + dia_6 + '
    'Q("clima_Lluvia ligera") + Q("clima_Lluvia moderada") + Q("clima_Lluvia intensa") + '
    'Q("clima_Niebla") + Q("clima_Nublado") + Q("clima_Tormenta")'),data=entrenamiento).fit()
print(modelo.summary())

predicciones = modelo.predict(test)

plt.figure(figsize=(7, 6))
plt.scatter(test["vehiculos"], predicciones, alpha=0.3, label='Predicciones')
plt.plot([0, 260], [0, 260], color='red', linestyle='--', label='Predicción perfecta')
plt.title('Regresión Lineal: Vehículos Reales vs. Predichos (Test)')
plt.xlabel('Vehículos reales')
plt.ylabel('Vehículos predichos por el modelo')
plt.grid(True, alpha=0.3)
plt.legend()
plt.tight_layout()
plt.show()